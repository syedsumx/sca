"""nightly-sales: Refresh the revenue mart, check it, report and tell the team

Generated by Cairn from the flow 'nightly-sales' (version 3), owned by ana. Change the flow in Cairn
and export it again (a flow with runner: airflow is deployed by Cairn on each publish).

No secrets: tasks sign in with Airflow's connection 'cairn_default' (a Cairn token of a pipeline user).
Native tasks run as that user; delegated tasks run in Cairn as the flow's owner, and need that user to be
the flow's owner, an editor or an admin in Cairn. Needs cairn-airflow-provider.
"""

from __future__ import annotations

import os
from datetime import datetime, timedelta

from airflow.providers.standard.operators.trigger_dagrun import TriggerDagRunOperator
from airflow.sdk import Asset, AssetWatcher, DAG, Param
from airflow.timetables.assets import AssetOrTimeSchedule
from airflow.timetables.trigger import CronTriggerTimetable

from cairn_airflow.flows import CairnFlowBranchOperator, CairnFlowStepOperator
from cairn_airflow.operators import CairnDbtOperator
from cairn_airflow.quality import CairnCheckOperator
from cairn_airflow.spark import CairnSparkApplicationOperator
from cairn_airflow.triggers import CairnDatasetChangedTrigger

FLOW = 'nightly-sales'
CONN = 'cairn_default'
# The Spark Operator's settings on this Airflow (no secrets: the driver signs in with its service
# account's projected token).
SPARK = {"image": os.environ.get("CAIRN_SPARK_IMAGE", ""),
         "service_account": os.environ.get("CAIRN_SPARK_SERVICE_ACCOUNT", "svc-spark"),
         "namespace": os.environ.get("CAIRN_SPARK_NAMESPACE", "default"),
         "cairn_url": os.environ.get("CAIRN_URL", ""),
         "catalog_uri": os.environ.get("CAIRN_CATALOG_URI", "")}
# The tables whose changes start a run, watched in Cairn's change feed.
ASSETS = [
    Asset('raw.orders', watchers=[AssetWatcher(
        name='cairn_changed_0',
        trigger=CairnDatasetChangedTrigger(['raw.orders'], cairn_conn_id=CONN))]),
]

# Trigger after flow ingest-orders (succeeded): no Airflow equivalent; Cairn starts the flow after it, or use an
# asset the other DAG updates.
# concurrency skip: Airflow queues a run while another is active (max_active_runs) rather than skipping it.
# SLA 90 minutes: Airflow 3 has no SLAs; use a deadline alert, or keep the flow in Cairn.
# Notifications (failure to urn:li:corpuser:bob): set Airflow's own callbacks for them.
with DAG(
    dag_id='nightly-sales',
    description='Refresh the revenue mart, check it, report and tell the team',
    schedule=AssetOrTimeSchedule(
        timetable=CronTriggerTimetable('0 2 * * *', timezone='Europe/Berlin'),
        assets=ASSETS),
    start_date=datetime(2026, 1, 1),
    catchup=False,
    max_active_runs=1,
    tags=['cairn', 'cairn-flow:nightly-sales', 'cairn-flow-version:3'],
    default_args={'owner': 'ana'},
    is_paused_upon_creation=False,
    doc_md=__doc__,
    params={
        'day': Param(None, type=['string', 'null'], description='(empty: Cairn fills in {{ run.logical_date }})'),
        'region': Param('EU', type='string', description='The region to report'),
        'min_rows': Param(1, type='integer'),
    },
) as dag:
    steps = {}
    # refresh (derived): delegated to Cairn: refreshing a derived table, as its owner.
    steps['refresh'] = CairnFlowStepOperator(
        task_id='refresh', retries=2, retry_delay=timedelta(seconds=60), retry_exponential_backoff=True,
        execution_timeout=timedelta(seconds=21600), flow=FLOW, step='refresh', cairn_conn_id=CONN,
    )
    # enough (check): on Trino as the connection's user (Cairn connection 'lakehouse' in the flow).
    steps['enough'] = CairnCheckOperator(
        task_id='enough', execution_timeout=timedelta(seconds=3600),
        sql="""SELECT count(*) AS n
FROM marts.revenue
WHERE region = '{{ params.region }}'""",
        measure='n', op='>=', value=1, cairn_conn_id=CONN,
    )
    steps['build'] = CairnDbtOperator(
        task_id='build', execution_timeout=timedelta(seconds=14400), project_dir='/dbt/sales', command='build',
        select='tag:nightly', cairn_conn_id=CONN,
    )
    steps['score'] = CairnSparkApplicationOperator(
        task_id='score', execution_timeout=timedelta(seconds=14400), name='score', main='s3a://jobs/score.py',
        arguments=['--day', '{{ params.day }}'], spark_conf={'spark.executor.instances': '2'}, **SPARK,
    )
    steps['export'] = TriggerDagRunOperator(
        task_id='export', execution_timeout=timedelta(seconds=21600), trigger_dag_id='partner_export',
        conf={'target': 's3'}, wait_for_completion=True, poke_interval=60,
    )
    # rows (sql): delegated to Cairn: other steps read its output, which Cairn keeps.
    steps['rows'] = CairnFlowStepOperator(
        task_id='rows', execution_timeout=timedelta(seconds=3600), flow=FLOW, step='rows', cairn_conn_id=CONN,
    )
    # big: a branch; Cairn evaluates 'steps.rows.rows > 10', Airflow skips the other side.
    steps['big'] = CairnFlowBranchOperator(
        task_id='big', execution_timeout=timedelta(seconds=60), flow=FLOW, step='big', then=['signoff'],
        otherwise=['note'], cairn_conn_id=CONN,
    )
    # signoff (approval): delegated to Cairn: an approval: people decide in Cairn (Flows, or the
    # notification).
    steps['signoff'] = CairnFlowStepOperator(
        task_id='signoff', execution_timeout=timedelta(seconds=259200), flow=FLOW, step='signoff',
        cairn_conn_id=CONN,
    )
    # note (notify): delegated to Cairn: a notification through Cairn's notification hub.
    steps['note'] = CairnFlowStepOperator(
        task_id='note', execution_timeout=timedelta(seconds=60), flow=FLOW, step='note', cairn_conn_id=CONN,
    )
    # each (for_each): delegated to Cairn: a for-each: Cairn runs each item.
    steps['each'] = CairnFlowStepOperator(
        task_id='each', execution_timeout=timedelta(seconds=21600), flow=FLOW, step='each', cairn_conn_id=CONN,
    )
    # done (notify): delegated to Cairn: a notification through Cairn's notification hub.
    steps['done'] = CairnFlowStepOperator(
        task_id='done', trigger_rule='all_done', execution_timeout=timedelta(seconds=120), flow=FLOW, step='done',
        cairn_conn_id=CONN,
    )

    steps['refresh'] >> steps['enough']
    steps['enough'] >> steps['build']
    steps['build'] >> steps['score']
    steps['build'] >> steps['export']
    steps['build'] >> steps['rows']
    steps['rows'] >> steps['big']
    steps['big'] >> steps['signoff']
    steps['big'] >> steps['note']
    steps['signoff'] >> steps['each']
    steps['each'] >> steps['done']
    steps['note'] >> steps['done']
    steps['score'] >> steps['done']
    steps['export'] >> steps['done']
