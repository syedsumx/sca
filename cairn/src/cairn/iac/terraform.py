"""Writes the Terraform provider's resource table from the registry (:mod:`cairn.iac.registry`).

``python -m cairn.iac.terraform`` writes ``terraform-provider-cairn/internal/provider/zz_generated_kinds.go`` and
the resource list in ``terraform-provider-cairn/README.md``; ``--check`` fails when either is out of date (CI runs
it through ``tests/test_iac_coverage.py``). The provider reads the table when Terraform starts it: its resources
are fixed at build time because Terraform asks for the provider's schema before it configures the provider (so
before it could ask any Cairn), and ``terraform validate`` works offline.
"""

from __future__ import annotations

import json
import os
import sys

from cairn.iac.registry import FAMILIES, UNSET, Field, Kind, Op, kinds

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "terraform-provider-cairn")
GO_FILE = os.path.join(ROOT, "internal", "provider", "zz_generated_kinds.go")
README = os.path.join(ROOT, "README.md")
BEGIN, END = "<!-- BEGIN GENERATED RESOURCES -->", "<!-- END GENERATED RESOURCES -->"


def go_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def go_strs(xs) -> str:
    return "[]string{" + ", ".join(go_str(x) for x in xs) + "}"


def go_default(f: Field) -> str:
    """The field's static default in Terraform (nil: none)."""
    d = f.default
    if d is UNSET or d is None or f.computed or f.type == "json" or f.write_only:
        return "nil"
    if f.type == "string":
        return go_str(d)
    if f.type == "bool":
        return "true" if d else "false"
    if f.type == "int":
        return f"int64({int(d)})"
    if f.type == "float":
        return f"float64({float(d)!r})"
    if f.type == "list":
        return go_strs(d)
    raise ValueError((f.name, f.type))


def go_field(k: Kind, f: Field) -> str:
    computed = f.computed or (f.type == "json" and f.default not in (UNSET, None) and not f.only_set)
    parts = [f"name: {go_str(f.tf_name)}", f"typ: {go_str(f.type)}"]
    if f.tf_name != f.name:
        parts.append(f"api: {go_str(f.name)}")
    if f.read:
        parts.append(f"read: {go_str(f.read)}")
    for flag, on in (("required", f.required), ("computed", computed and not f.required),
                     ("forceNew", f.force_new or k.immutable), ("sensitive", f.sensitive or f.write_only),
                     ("writeOnly", f.write_only), ("onlySet", f.only_set)):
        if on:
            parts.append(f"{flag}: true")
    d = go_default(f)
    if d != "nil":
        parts.append(f"def: {d}")
    if f.description:
        parts.append(f"desc: {go_str(f.description)}")
    return "{" + ", ".join(parts) + "}"


def go_op(o: Op | None) -> str:
    if o is None:
        return "nil"
    parts = [f"method: {go_str(o.method)}", f"path: {go_str(o.path)}"]
    if o.omit:
        parts.append(f"omit: {go_strs(o.omit)}")
    if o.only:
        parts.append(f"only: {go_strs(o.only)}")
    if o.body is not None:
        parts.append(f"body: {go_str(json.dumps(o.body, sort_keys=True))}")
    if o.no_body:
        parts.append("noBody: true")
    return "&op{" + ", ".join(parts) + "}"


def go_kind(k: Kind) -> str:
    lines = [f"\t{{typeName: {go_str(k.tf)}, name: {go_str(k.name)},",
             f"\t\tdesc: {go_str(k.description)},",
             f"\t\tread: {go_str(k.read)}, listKey: {go_str(k.list_key)}, idKey: {go_str(k.id)},",
             ]
    extra = [f"key: {go_strs(k.key)}, parents: {go_strs(k.parents)}, lookup: {go_str(k.lookup_field)}"]
    if k.mine:
        extra.append(f"mine: true, ownerField: {go_str(k.owner_field)}")
    if k.match:
        extra.append(f"match: {go_str(json.dumps(dict(k.match), sort_keys=True))}")
    lines.append("\t\t" + ", ".join(extra) + ",")
    lines.append(f"\t\tcreate: {go_op(k.create)}, update: {go_op(k.update)}, del: {go_op(k.delete)},")
    lines.append("\t\tfields: []field{")
    for f in k.fields:
        lines.append(f"\t\t\t{go_field(k, f)},")
    lines.append("\t\t}},")
    return "\n".join(lines)


def go_source() -> str:
    body = "\n".join(go_kind(k) for k in kinds())
    return ("// Code generated by python -m cairn.iac.terraform from Cairn's resource registry\n"
            "// (src/cairn/iac/registry.py); DO NOT EDIT.\n\n"
            "package provider\n\n"
            "// kinds are Cairn's configurable resource types, each a resource and a data source.\n"
            f"var kinds = []kind{{\n{body}\n}}\n")


def readme_table() -> str:
    out = [BEGIN, "", f"{len(kinds())} resources, each also a data source:", ""]
    for fam, title in FAMILIES.items():
        ks = [k for k in kinds() if k.family == fam]
        if not ks:
            continue
        out += [f"**{title}**", "", "| Resource | Bundle section | What it is |", "|---|---|---|"]
        for k in ks:
            desc = k.description.split(". ")[0].rstrip(".").replace("|", "\\|")
            out.append(f"| `cairn_{k.tf}` | `{k.name}` | {desc} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def readme(text: str) -> str:
    if BEGIN not in text:
        raise SystemExit(f"{README}: no {BEGIN} marker")
    a, rest = text.split(BEGIN, 1)
    _, b = rest.split(END, 1)
    return a + readme_table() + b


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    want = {GO_FILE: go_source(), README: readme(open(README).read())}
    stale = [p for p, text in want.items() if not os.path.exists(p) or open(p).read() != text]
    if check:
        for p in stale:
            print(f"out of date: {os.path.relpath(p)} (run python -m cairn.iac.terraform)")
        return 1 if stale else 0
    for p in stale:
        with open(p, "w") as fh:
            fh.write(want[p])
        print(f"wrote {os.path.relpath(p)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
