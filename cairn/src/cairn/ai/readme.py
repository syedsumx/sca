"""Markdown "living README" for an asset: AI-drafted when an LLM is configured, else assembled."""

from __future__ import annotations

from typing import Optional

from cairn.ai.catalog import Catalog


def _cell(text: Optional[str]) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def assemble_markdown(urn: str, catalog: Catalog, quality_store=None, attributes=None,
                      draft: Optional[dict] = None) -> str:
    details = catalog.details(urn) or {"urn": urn}
    name = (details.get("properties") or {}).get("name") or details.get("name") or urn
    platform = (details.get("platform") or {}).get("name")
    desc = (draft or {}).get("description") or (details.get("editableProperties") or {}).get("description") \
        or (details.get("properties") or {}).get("description") or "_No description yet._"
    lines = [f"# {name}", ""]
    meta = [f"**Platform:** {platform}" if platform else None]
    dom = (((details.get("domain") or {}).get("domain") or {}).get("properties") or {}).get("name")
    if dom:
        meta.append(f"**Domain:** {dom}")
    owners = [((o.get("owner") or {}).get("username") or (o.get("owner") or {}).get("name") or
               (o.get("owner") or {}).get("urn")) for o in ((details.get("ownership") or {}).get("owners") or [])]
    if owners:
        meta.append(f"**Owners:** {', '.join(filter(None, owners))}")
    if attributes is not None:
        res = attributes.resource(urn)
        if res.get("certification"):
            meta.append(f"**Certification:** {res['certification']}")
        if res.get("classification"):
            meta.append(f"**Sensitivity:** {', '.join(res['classification'])}")
    lines += [" · ".join(m for m in meta if m), ""]
    if draft and draft.get("summary"):
        lines += [f"> {draft['summary']}", ""]
    lines += ["## What it is", "", desc, ""]
    fields = ((details.get("schemaMetadata") or {}).get("fields")) or []
    if fields:
        drafted = {c["field_path"]: c["description"] for c in (draft or {}).get("columns", [])}
        edits = {f["fieldPath"]: f.get("description") for f in
                 ((details.get("editableSchemaMetadata") or {}).get("editableSchemaFieldInfo") or [])}
        lines += ["## Columns", "", "| Column | Type | Description |", "|---|---|---|"]
        for f in fields[:200]:
            d = edits.get(f["fieldPath"]) or f.get("description") or drafted.get(f["fieldPath"]) or ""
            lines.append(f"| `{_cell(f['fieldPath'])}` | {_cell(f.get('nativeDataType'))} | {_cell(d)} |")
        lines.append("")
    try:
        ups = catalog.lineage(urn, "UPSTREAM", 1, 10)
        downs = catalog.lineage(urn, "DOWNSTREAM", 1, 10)
    except Exception:
        ups, downs = [], []
    if ups or downs:
        lines += ["## Lineage", ""]
        if ups:
            lines.append("**Built from:** " + ", ".join(f"`{u['name']}`" for u in ups))
        if downs:
            lines.append("**Used by:** " + ", ".join(f"`{d['name']}`" for d in downs))
        lines.append("")
    if quality_store is not None:
        monitors = quality_store.list_monitors(urn)
        if monitors:
            lines += ["## Quality", "", "| Monitor | Type | Status |", "|---|---|---|"]
            for m in monitors:
                st = m.last_evaluation.status if m.last_evaluation else "NEVER RUN"
                lines.append(f"| {_cell(m.name)} | {m.type} | {st} |")
            lines.append("")
    if draft and draft.get("unknowns"):
        lines += ["## Open questions", ""] + [f"- {u}" for u in draft["unknowns"]] + [""]
    lines.append("_Generated by Cairn" + (f" with {draft.get('model')}" if draft and draft.get("model")
                                                      else "") + "._")
    return "\n".join(lines)
